pub const fn scale2x(g: [u8; 8]) -> [u16; 16] {
    const fn px(g: &[u8; 8], x: isize, y: isize) -> bool {
        if x < 0 || y < 0 || x >= 8 || y >= 8 { false } else { (g[y as usize] >> x) & 1 == 1 }
    }
    let mut out = [0u16; 16];
    let mut y = 0isize;
    while y < 8 {
        let mut x = 0isize;
        while x < 8 {
            let e = px(&g, x, y);
            let b = px(&g, x, y - 1); // arriba
            let h = px(&g, x, y + 1); // abajo
            let d = px(&g, x - 1, y); // izquierda
            let f = px(&g, x + 1, y); // derecha
            let (e0, e1, e2, e3) = if b != h && d != f {
                (
                    if d == b { d } else { e },
                    if b == f { f } else { e },
                    if d == h { d } else { e },
                    if h == f { f } else { e },
                )
            } else {
                (e, e, e, e)
            };
            let bx = (2 * x) as u32;
            let top = (2 * y) as usize;
            out[top] |= (e0 as u16) << bx | (e1 as u16) << (bx + 1);
            out[top + 1] |= (e2 as u16) << bx | (e3 as u16) << (bx + 1);
            x += 1;
        }
        y += 1;
    }
    out
}

/// Tabla ASCII 16x16 calculada al compilar.
static ASCII16: [[u16; 16]; 96] = {
    let mut t = [[0u16; 16]; 96];
    let mut i = 0;
    while i < 96 {
        t[i] = scale2x(BASIC[i]);
        i += 1;
    }
    t
};

/// Glifo suavizado de 16x16 (bit 0 = izquierda).
pub fn glyph16(c: char) -> [u16; 16] {
    match c as u32 {
        0x20..=0x7F => ASCII16[(c as u32 - 0x20) as usize],
        _ => {
            let g = glyph8(c);
            // Las líneas de caja y los bloques no se suavizan: deben empalmar.
            if matches!(c as u32, 0x2500..=0x259F) {
                let mut out = [0u16; 16];
                let mut i = 0;
                while i < 16 {
                    let row = g[i / 2];
                    let mut bits = 0u16;
                    let mut x = 0;
                    while x < 8 {
                        if row >> x & 1 == 1 {
                            bits |= 0b11 << (2 * x);
                        }
                        x += 1;
                    }
                    out[i] = bits;
                    i += 1;
                }
                out
            } else {
                scale2x(g)
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn draw8(g: [u8; 8]) -> String {
        g.iter()
            .map(|r| (0..8).map(|x| if r >> x & 1 == 1 { '#' } else { '.' }).collect::<String>())
            .collect::<Vec<_>>()
            .join("\n")
    }

    #[test]
    fn la_a_se_ve_como_una_a() {
        assert_eq!(
            draw8(glyph8('A')),
            "..##....\n.####...\n##..##..\n##..##..\n######..\n##..##..\n##..##..\n........"
        );
    }

    #[test]
    fn interrogacion_invertida() {
        let q = glyph8('¿');
        // El punto queda arriba y la curva abajo.
        assert_ne!(q[1], 0);
        assert_eq!(q[2], 0);
        assert_ne!(q[7], 0);
        assert!(has_glyph('¿') && has_glyph('ñ') && has_glyph('╔'));
    }

    #[test]
    fn acentos_sobre_la_letra() {
        let e = glyph8('é');
        assert_eq!((e[0], e[1]), ACUTE);
        assert_eq!(&e[2..], &basic(b'e')[2..]);
        let n = glyph8('ñ');
        assert_eq!((n[0], n[1]), TILDE);
    }

    #[test]
    fn scale2x_conserva_bloques_y_suaviza_diagonales() {
        // Scale2x redondea las esquinas de un bloque macizo (el borde es "vacío")...
        assert_eq!(scale2x([0xFF; 8])[0], 0x7FFE);
        // ...por eso los bloques y las cajas se escalan sin suavizar: deben empalmar.
        assert_eq!(glyph16('█'), [0xFFFF; 16]);
        assert_eq!(scale2x([0; 8]), [0; 16]);
        // Una diagonal: un 2x "a lo bruto" daría 8 bloques de 4 píxeles (32) en
        // escalera; Scale2x rellena los escalones, así que salen más.
        let diag = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80];
        let s = scale2x(diag);
        let count: u32 = s.iter().map(|r| r.count_ones()).sum();
        assert!(count > 8 * 4 && count < 8 * 8, "{count}");
        assert_eq!(glyph16('A'), scale2x(glyph8('A')));
    }

    #[test]
    fn las_cajas_empalman() {
        let h = glyph16('─');
        let v = glyph16('│');
        assert_eq!(h[6], 0xFFFF);
        assert!(v.iter().all(|&r| r == v[0] && r != 0));
    }
}
