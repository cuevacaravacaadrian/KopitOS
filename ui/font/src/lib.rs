/// ¿Tenemos un glifo propio para `c`?
pub fn has_glyph(c: char) -> bool {
    matches!(c as u32, 0x20..=0x7E) || extended(c).is_some()
}

/// Glifo de 8x8 (bit 0 = izquierda).
pub fn glyph8(c: char) -> [u8; 8] {
    match c as u32 {
        0x20..=0x7F => basic(c as u8),
        _ => extended(c).unwrap_or(MISSING),
    }
}

