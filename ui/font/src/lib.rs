/// Glifo de reemplazo (caja hueca) para lo que no sabemos dibujar.
const MISSING: [u8; 8] = [0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00];

const fn basic(c: u8) -> [u8; 8] {
    BASIC[(c - 0x20) as usize]
}

/// Marca de dos filas encima de una minúscula (sus filas 0-1 están vacías).
const fn mark2(base: [u8; 8], r0: u8, r1: u8) -> [u8; 8] {
    [r0, r1, base[2], base[3], base[4], base[5], base[6], base[7]]
}

/// Mayúscula: se baja una fila y se pone una marca de una fila encima.
const fn mark_upper(base: [u8; 8], r0: u8) -> [u8; 8] {
    [r0, base[0], base[1], base[2], base[3], base[4], base[5], base[6]]
}

/// Gira 180° (para ¿ y ¡) y recentra.
const fn rotate180(g: [u8; 8]) -> [u8; 8] {
    let mut out = [0u8; 8];
    let mut i = 0;
    while i < 8 {
        out[i] = g[7 - i].reverse_bits() >> 1;
        i += 1;
    }
    out
}

