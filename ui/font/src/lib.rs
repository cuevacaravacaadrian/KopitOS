//! # Fuente de la consola de KopitOS
//!
//! * **Base**: `font8x8_basic` de Daniel Hepper (dominio público), derivada
//!   de la fuente de 8x8 del IBM PC. Cada glifo son 8 filas de 8 bits y el
//!   **bit 0 es el píxel de la izquierda**.
//! * **Español completo**: á é í ó ú ü ñ ç (y mayúsculas), ¿ ¡ º ª « » € ·
//!   se *componen* a partir de la letra base y una marca, sin almacenar
//!   cientos de glifos: ¿ es ? girada 180°, é es e con un acento encima...
//! * **Interfaz**: líneas y esquinas de caja, bloques, flechas, ✓ ✗ ▶ ●.
//! * **Escalado suave Scale2x** (AdvanceMAME): al doblar el tamaño, en vez
//!   de bloques gordos se suavizan las diagonales. La tabla ASCII de 16x16 se
//!   calcula **al compilar** (`const fn`), así que no cuesta nada en tiempo de
//!   ejecución.

